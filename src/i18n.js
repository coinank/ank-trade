const LANGS = ['zh_CN', 'zh_TW', 'en'];
let _lang = 'zh_CN';
let _msgs = MESSAGES.zh_CN;

export async function initLang() {
  const s = await chrome.storage.local.get('lang');
  if (s.lang && MESSAGES[s.lang]) {
    _lang = s.lang;
    _msgs = MESSAGES[_lang];
  }
}

export function t(key, vars = {}) {
  let str = _msgs[key] ?? MESSAGES.zh_CN[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
  }
  return str;
}

export function langLabel() { return _msgs.lang_label; }

export async function cycleLang() {
  const idx = LANGS.indexOf(_lang);
  _lang = LANGS[(idx + 1) % LANGS.length];
  _msgs = MESSAGES[_lang];
  await chrome.storage.local.set({ lang: _lang });
}
